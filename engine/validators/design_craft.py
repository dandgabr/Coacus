"""Deterministic Design Craft and Anti-AI-Slop Validator (Python Standard Library only).

Detects visual clichés, low-contrast combinations and structural tells
commonly generated by AI coding assistants.
"""

from __future__ import annotations

import re
from dataclasses import dataclass
from pathlib import Path
from typing import Sequence

SUPPORTED_EXTENSIONS = {
    ".html", ".htm", ".jsx", ".tsx", ".vue", ".svelte", ".astro", ".css", ".scss", ".md"
}

# Saturated chromatic backgrounds commonly paired erroneously with muted gray text
CHROMATIC_BG_RE = re.compile(
    r"\bbg-(?:red|blue|green|emerald|indigo|purple|violet|amber|yellow|cyan|sky|rose|pink|fuchsia|teal)-(?:500|600|700|800)\b"
)
# Low-contrast gray text classes
MUTED_GRAY_TEXT_RE = re.compile(
    r"\btext-(?:gray|slate|zinc|neutral|stone)-(?:400|500)\b"
)

# AI gradient staples (purple/indigo/violet to blue/fuchsia/pink)
AI_GRADIENT_RE = re.compile(
    r"\bfrom-(?:indigo|purple|violet)-(?:500|600)\s+to-(?:blue|fuchsia|pink|purple)-(?:500|600)\b"
)

# Single italic serif emphasis inside headings
ITALIC_SERIF_WORD_RE = re.compile(
    r"<h[1-6][^>]*>.*?<(?:span|em)[^>]*class(?:Name)?=[\"'][^\"']*\bfont-serif\b[^\"']*\bitalic\b[^\"']*[\"'][^>]*>([^<]+)</(?:span|em)>.*?</h[1-6]>",
    re.IGNORECASE | re.DOTALL,
)

# Hero eyebrow pill badges
HERO_EYEBROW_PILL_RE = re.compile(
    r"<(?:div|span|a)[^>]*class(?:Name)?=[\"'][^\"']*\brounded-full\b[^\"']*[\"'][^>]*>.*?(?:sparkle|introducing|announcing|new\b|v[0-9]|✨|🚀).*?</(?:div|span|a)>",
    re.IGNORECASE | re.DOTALL,
)

# Bounce or exaggerated elastic easing curves
BOUNCE_EASING_RE = re.compile(
    r"cubic-bezier\(\s*0?\.\d+\s*,\s*-\d+(?:\.\d+)?\s*,\s*0?\.\d+\s*,\s*[1-9](?:\.\d+)?\s*\)"
)

# Icon in small rounded box pattern (e.g., rounded-lg p-2 bg-indigo-50 before heading)
ICON_TILE_RE = re.compile(
    r"<(?:div|span)[^>]*class(?:Name)?=[\"'][^\"']*\brounded-(?:md|lg|xl|2xl)\b[^\"']*\bbg-[a-z]+-(?:50|100|500/10)\b[^\"']*[\"'][^>]*>.*?<svg",
    re.IGNORECASE | re.DOTALL,
)


@dataclass(frozen=True)
class DesignFinding:
    """Represents a single detected design anti-pattern or accessibility issue."""

    rule_id: str
    message: str
    line: int
    file_path: str = ""
    severity: str = "warning"

    def format_line(self) -> str:
        """Return a human-readable string representation of the finding."""
        loc = f"{self.file_path}:{self.line}" if self.file_path else f"line {self.line}"
        return f"[{self.severity.upper()}] {loc} ({self.rule_id}): {self.message}"


def _line_number_at_offset(text: str, offset: int) -> int:
    return text.count("\n", 0, offset) + 1


def scan_text(content: str, file_path: str = "") -> list[DesignFinding]:
    """Scan raw text content for design anti-patterns."""
    findings: list[DesignFinding] = []
    lines = content.splitlines()

    # Line-by-line scans
    for idx, line in enumerate(lines, start=1):
        # 1. Gray text on chromatic background
        if CHROMATIC_BG_RE.search(line) and MUTED_GRAY_TEXT_RE.search(line):
            # Check if they are co-located in the same tag/attribute
            findings.append(
                DesignFinding(
                    rule_id="gray-on-color",
                    message="Low-contrast muted gray text paired with solid chromatic background fill",
                    line=idx,
                    file_path=file_path,
                )
            )

        # 2. Cliché AI gradient
        if AI_GRADIENT_RE.search(line):
            findings.append(
                DesignFinding(
                    rule_id="ai-color-palette",
                    message="Generic AI purple-to-blue gradient detected; use intentional, brand-specific color ramps",
                    line=idx,
                    file_path=file_path,
                )
            )

        # 3. Bounce easing
        if BOUNCE_EASING_RE.search(line):
            findings.append(
                DesignFinding(
                    rule_id="bounce-easing",
                    message="Exaggerated bounce/elastic easing detected; use calibrated spring or linear/ease-out curves under 200ms",
                    line=idx,
                    file_path=file_path,
                )
            )

        # 4. Em-dash overuse
        em_dash_count = line.count("—")
        if em_dash_count >= 3 and len(line) < 300:
            findings.append(
                DesignFinding(
                    rule_id="em-dash-overuse",
                    message=f"Excessive em-dash cadence detected ({em_dash_count} in single line); simplify prose rhythm",
                    line=idx,
                    file_path=file_path,
                )
            )

    # Multi-line structural scans
    for match in ITALIC_SERIF_WORD_RE.finditer(content):
        line_num = _line_number_at_offset(content, match.start())
        findings.append(
            DesignFinding(
                rule_id="italic-serif",
                message=f"Formulaic isolated italic serif word '{match.group(1).strip()}' in headline; commit to a unified type hierarchy",
                line=line_num,
                file_path=file_path,
            )
        )

    for match in HERO_EYEBROW_PILL_RE.finditer(content):
        line_num = _line_number_at_offset(content, match.start())
        findings.append(
            DesignFinding(
                rule_id="hero-eyebrow",
                message="Formulaic hero eyebrow pill badge detected; use a clean typographic kicker or integrate into headline",
                line=line_num,
                file_path=file_path,
            )
        )

    for match in ICON_TILE_RE.finditer(content):
        line_num = _line_number_at_offset(content, match.start())
        findings.append(
            DesignFinding(
                rule_id="icon-tile",
                message="Formulaic icon tile in pastel container; place icon inline with text or let typography lead",
                line=line_num,
                file_path=file_path,
            )
        )

    return findings


def scan_file(path: Path) -> list[DesignFinding]:
    """Scan a single file if it has a supported frontend extension."""
    if path.suffix.lower() not in SUPPORTED_EXTENSIONS:
        return []
    try:
        content = path.read_text(encoding="utf-8", errors="replace")
    except OSError:
        return []
    return scan_text(content, str(path))


def scan_directory(root: Path) -> list[DesignFinding]:
    """Recursively scan a directory for design anti-patterns."""
    findings: list[DesignFinding] = []
    ignored_parts = {".git", "node_modules", "dist", "build", ".next", ".agents", "scratch"}
    for file_path in root.rglob("*"):
        if not file_path.is_file():
            continue
        if any(part in ignored_parts for part in file_path.parts):
            continue
        findings.extend(scan_file(file_path))
    return findings
