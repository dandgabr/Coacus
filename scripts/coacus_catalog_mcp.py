#!/usr/bin/env python3
"""Serve the installed Coacus catalog to Antigravity over MCP stdio.

The runtime reads one deterministic index generated by the installer. It does
not scan the corpus on each request; source files are opened only on demand.
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path, PurePosixPath
from typing import TextIO

MAX_RESULTS = 8
SUPPORTED_PROTOCOLS = frozenset(
    {"2025-11-25", "2025-06-18", "2025-03-26", "2024-11-05"}
)
PROTOCOL_FALLBACK = "2025-11-25"
SERVER_VERSION = "1.0.0"

TOOLS = [
    {
        "name": "search",
        "description": "Find Coacus skills or agents by name, category, or task intent.",
        "inputSchema": {
            "type": "object",
            "properties": {
                "query": {"type": "string", "minLength": 1, "maxLength": 256},
                "kind": {"type": "string", "enum": ["all", "skill", "agent"]},
                "limit": {"type": "integer", "minimum": 1, "maximum": MAX_RESULTS},
            },
            "required": ["query"],
        },
    },
    {
        "name": "get",
        "description": "Load one complete canonical Coacus skill or agent instruction on demand.",
        "inputSchema": {
            "type": "object",
            "properties": {
                "kind": {"type": "string", "enum": ["skill", "agent"]},
                "name": {"type": "string", "minLength": 1, "maxLength": 128},
            },
            "required": ["kind", "name"],
        },
    },
    {
        "name": "get_reference",
        "description": "Load a supporting file linked by a Coacus skill or agent.",
        "inputSchema": {
            "type": "object",
            "properties": {
                "kind": {"type": "string", "enum": ["skill", "agent"]},
                "name": {"type": "string", "minLength": 1, "maxLength": 128},
                "path": {"type": "string", "minLength": 1, "maxLength": 512},
            },
            "required": ["kind", "name", "path"],
        },
    },
]


def _parse_frontmatter(text: str) -> dict[str, object]:
    """Extract name, description, and skills from a canonical frontmatter block."""
    if not text.startswith("---"):
        return {}
    lines = text.splitlines()
    if not lines or lines[0].strip() != "---":
        return {}
    meta: dict[str, object] = {}
    current_key: str | None = None
    list_items: list[str] = []
    in_block_scalar = False
    block_lines: list[str] = []

    for line in lines[1:]:
        stripped = line.strip()
        if stripped == "---":
            break
        if in_block_scalar:
            if line.startswith("  ") or not stripped:
                block_lines.append(stripped)
                continue
            else:
                meta[current_key] = " ".join(block_lines).strip()
                in_block_scalar = False
                current_key = None
        if current_key and stripped.startswith("- "):
            list_items.append(stripped[2:].strip().strip('"\''))
            meta[current_key] = list(list_items)
            continue
        elif current_key and list_items:
            current_key = None
            list_items = []

        if ":" in line and not line.startswith(" "):
            key, val = line.split(":", 1)
            key = key.strip()
            val = val.strip()
            if val in (">-", ">", "|", "|-"):
                in_block_scalar = True
                current_key = key
                block_lines = []
            elif val.startswith("[") and val.endswith("]"):
                items = [item.strip().strip('"\'') for item in val[1:-1].split(",") if item.strip()]
                meta[key] = items
                current_key = None
            elif not val:
                current_key = key
                list_items = []
            else:
                meta[key] = val.strip('"\'')
                current_key = None
    if in_block_scalar and current_key:
        meta[current_key] = " ".join(block_lines).strip()
    return meta


try:
    from engine.frontmatter import parse as _fm_parse

    def _get_frontmatter(text: str) -> dict[str, object]:
        try:
            return _fm_parse(text).meta
        except Exception:
            return _parse_frontmatter(text)
except ImportError:
    def _get_frontmatter(text: str) -> dict[str, object]:
        return _parse_frontmatter(text)


class Catalog:
    """Read the prebuilt index or repository corpus and resolve capability files safely."""

    def __init__(self, install_root: Path):
        self.install_root = install_root.resolve()
        if not (self.install_root / "catalog").is_dir() and (self.install_root.parent / "catalog").is_dir():
            self.install_root = self.install_root.parent
        index_path = self.install_root / "catalog" / "index.json"
        if index_path.is_file():
            try:
                index = json.loads(index_path.read_text(encoding="utf-8"))
            except (OSError, json.JSONDecodeError) as exc:
                raise ValueError(f"cannot read Coacus catalog index: {exc}") from exc
            if not isinstance(index, dict) or index.get("schema") != 1:
                raise ValueError("unsupported or malformed Coacus catalog index")
            self._load_from_index(index)
        elif (self.install_root / "catalog" / "catalog.json").is_file() or (self.install_root / "knowledge" / "skills").is_dir():
            self._load_from_repo()
        else:
            raise ValueError(f"cannot read Coacus catalog index at {index_path}")

    def _load_from_index(self, index: dict) -> None:
        self._entries: dict[str, dict[str, dict]] = {"skill": {}, "agent": {}}
        for kind in self._entries:
            rows = index.get(kind + "s")
            if not isinstance(rows, list):
                raise ValueError(f"catalog index has no {kind}s list")
            for row in rows:
                if not isinstance(row, dict):
                    raise ValueError(f"catalog contains a malformed {kind} entry")
                name = str(row.get("name") or "")
                payload = str(row.get("payload") or "")
                if not name or name in self._entries[kind] or not payload:
                    raise ValueError(f"catalog contains an invalid or duplicate {kind} entry")
                self._safe_path(payload)
                self._entries[kind][name] = row

    def _load_from_repo(self) -> None:
        import hashlib

        self._entries: dict[str, dict[str, dict]] = {"skill": {}, "agent": {}}
        skills_dir = self.install_root / "knowledge" / "skills"
        workflow_dir = self.install_root / "methodology" / "workflows"
        skill_files: list[Path] = []
        if skills_dir.is_dir():
            skill_files.extend(sorted(skills_dir.rglob("SKILL.md")))
        if workflow_dir.is_dir():
            skill_files.extend(sorted(workflow_dir.rglob("SKILL.md")))

        skill_names_by_source: dict[str, str] = {}
        for sf in skill_files:
            try:
                rel = sf.relative_to(self.install_root).as_posix()
            except ValueError:
                continue
            text = sf.read_text(encoding="utf-8")
            meta = _get_frontmatter(text)
            name = str(meta.get("name") or sf.parent.name)
            if rel.startswith("knowledge/skills/"):
                category = "/".join(sf.relative_to(skills_dir).parts[:-2])
            else:
                category = "workflows"
            skill_names_by_source[rel] = name
            entry = {
                "name": name,
                "kind": "skill",
                "category": category,
                "description": str(meta.get("description") or ""),
                "source": rel,
                "payload": rel,
                "fingerprint": hashlib.sha256(sf.read_bytes()).hexdigest(),
            }
            self._safe_path(rel)
            self._entries["skill"][name] = entry

        agents_dir = self.install_root / "knowledge" / "agents"
        agent_files: list[Path] = []
        if agents_dir.is_dir():
            agent_files.extend(sorted(agents_dir.rglob("agent.source.md")))

        for af in agent_files:
            try:
                rel = af.relative_to(self.install_root).as_posix()
            except ValueError:
                continue
            text = af.read_text(encoding="utf-8")
            meta = _get_frontmatter(text)
            name = str(meta.get("name") or af.parent.name)
            category = str(af.relative_to(agents_dir).parts[0])
            skill_paths = meta.get("skills", [])
            if not isinstance(skill_paths, list):
                skill_paths = []
            associated_skills = sorted(
                {
                    skill_names_by_source[str(p)]
                    for p in skill_paths
                    if str(p) in skill_names_by_source
                }
            )
            entry = {
                "name": name,
                "kind": "agent",
                "category": category,
                "description": str(meta.get("description") or ""),
                "source": rel,
                "payload": rel,
                "fingerprint": hashlib.sha256(af.read_bytes()).hexdigest(),
                "skills": associated_skills,
            }
            self._safe_path(rel)
            self._entries["agent"][name] = entry

    def search(self, query: str, kind: str = "all", limit: int = MAX_RESULTS) -> list[dict]:
        """Return a deterministic, bounded list of matching capabilities."""
        query = query.strip()
        if not query or len(query) > 256:
            raise ValueError("query must contain 1 to 256 characters")
        if kind not in ("all", "skill", "agent"):
            raise ValueError("kind must be all, skill, or agent")
        if not isinstance(limit, int) or isinstance(limit, bool) or not 1 <= limit <= MAX_RESULTS:
            raise ValueError(f"limit must be between 1 and {MAX_RESULTS}")
        tokens = [token.casefold() for token in re.findall(r"[\w-]+", query)]
        if not tokens:
            raise ValueError("query must contain searchable characters")

        ranked: list[tuple[int, str, str, dict]] = []
        kinds = (kind,) if kind != "all" else ("skill", "agent")
        for current_kind in kinds:
            for name, row in self._entries[current_kind].items():
                description = str(row.get("description") or "")
                category = str(row.get("category") or "")
                haystack = f"{name} {category} {description}".casefold()
                matched = sum(token in haystack for token in tokens)
                if not matched:
                    continue
                folded_name = name.casefold()
                score = matched * 10
                if query.casefold() == folded_name:
                    score += 100
                elif folded_name.startswith(query.casefold()):
                    score += 30
                elif query.casefold() in folded_name:
                    score += 20
                if all(token in haystack for token in tokens):
                    score += 5
                ranked.append(
                    (
                        -score,
                        current_kind,
                        folded_name,
                        {
                            "name": name,
                            "kind": current_kind,
                            "category": category,
                            "description": description,
                            "source": row.get("source", ""),
                        },
                    )
                )
        ranked.sort(key=lambda item: item[:3])
        return [item[3] for item in ranked[:limit]]

    def get(self, name: str, kind: str) -> dict:
        """Return a canonical body and metadata for one exact capability."""
        row = self._entry(name, kind)
        path = self._safe_path(str(row["payload"]))
        try:
            content = path.read_text(encoding="utf-8")
        except OSError as exc:
            raise FileNotFoundError(f"installed source for {kind} {name!r} is unavailable") from exc
        return {
            "name": name,
            "kind": kind,
            "category": row.get("category", ""),
            "source": row.get("source", ""),
            "fingerprint": row.get("fingerprint", ""),
            "associated_skills": row.get("skills", []) if kind == "agent" else [],
            "content": content,
        }

    def get_reference(self, name: str, relative_path: str, kind: str = "skill") -> dict:
        """Read a referenced sibling file without permitting path escape."""
        row = self._entry(name, kind)
        pure_path = PurePosixPath(relative_path)
        if (
            pure_path.is_absolute()
            or not relative_path
            or "\\" in relative_path
            or ":" in relative_path
            or any(part in ("", ".", "..") for part in pure_path.parts)
        ):
            raise ValueError("reference path must be relative and stay inside the capability directory")
        source_path = self._safe_path(str(row["payload"]))
        capability_root = source_path.parent
        candidate = (capability_root / Path(*pure_path.parts)).resolve()
        if not _is_within(candidate, capability_root.resolve()):
            raise ValueError("reference path escapes the capability directory")
        if not candidate.is_file():
            raise FileNotFoundError(f"reference {relative_path!r} was not found for {kind} {name!r}")
        return {"name": name, "kind": kind, "path": relative_path, "content": candidate.read_text(encoding="utf-8")}

    def _entry(self, name: str, kind: str) -> dict:
        if kind not in self._entries:
            raise ValueError("kind must be skill or agent")
        try:
            return self._entries[kind][name]
        except KeyError as exc:
            raise KeyError(f"no Coacus {kind} named {name!r}") from exc

    def _safe_path(self, relative_path: str) -> Path:
        pure_path = PurePosixPath(relative_path)
        if (
            pure_path.is_absolute()
            or not relative_path
            or "\\" in relative_path
            or ":" in relative_path
            or any(part in ("", ".", "..") for part in pure_path.parts)
        ):
            raise ValueError("catalog payload path must be relative and contain no traversal")
        resolved = (self.install_root / Path(*pure_path.parts)).resolve()
        if not _is_within(resolved, self.install_root):
            raise ValueError("catalog payload path escapes the installation root")
        return resolved


def _is_within(path: Path, root: Path) -> bool:
    try:
        path.relative_to(root)
        return True
    except ValueError:
        return False


def handle_message(message: dict, catalog: Catalog) -> dict | None:
    """Handle one MCP JSON-RPC message; return None for notifications."""
    if not isinstance(message, dict) or message.get("jsonrpc") != "2.0":
        return {"jsonrpc": "2.0", "id": message.get("id") if isinstance(message, dict) else None,
                "error": {"code": -32600, "message": "Invalid Request"}}
    method = message.get("method")
    request_id = message.get("id")
    if not isinstance(method, str):
        return {"jsonrpc": "2.0", "id": request_id, "error": {"code": -32600, "message": "Invalid Request"}}
    if method.startswith("notifications/"):
        return None
    if method == "initialize":
        params = message.get("params") if isinstance(message.get("params"), dict) else {}
        requested_version = params.get("protocolVersion")
        if not isinstance(requested_version, str) or not requested_version:
            return {
                "jsonrpc": "2.0",
                "id": request_id,
                "error": {
                    "code": -32602,
                    "message": "Invalid params: protocolVersion is required",
                },
            }
        version = (
            requested_version
            if requested_version in SUPPORTED_PROTOCOLS
            else PROTOCOL_FALLBACK
        )
        return {
            "jsonrpc": "2.0",
            "id": request_id,
            "result": {
                "protocolVersion": version,
                "capabilities": {"tools": {}},
                "serverInfo": {"name": "coacus-catalog", "version": SERVER_VERSION},
                "instructions": "Search the installed Coacus catalog, then load only the selected source.",
            },
        }
    if method == "ping":
        return {"jsonrpc": "2.0", "id": request_id, "result": {}}
    if method == "tools/list":
        return {"jsonrpc": "2.0", "id": request_id, "result": {"tools": TOOLS}}
    if method == "tools/call":
        params = message.get("params") if isinstance(message.get("params"), dict) else {}
        try:
            result = _call_tool(str(params.get("name") or ""), params.get("arguments") or {}, catalog)
            tool_result = {"content": [{"type": "text", "text": json.dumps(result, ensure_ascii=False)}]}
        except (KeyError, ValueError, FileNotFoundError, TypeError) as exc:
            tool_result = {"content": [{"type": "text", "text": str(exc)}], "isError": True}
        return {"jsonrpc": "2.0", "id": request_id, "result": tool_result}
    return {"jsonrpc": "2.0", "id": request_id, "error": {"code": -32601, "message": f"Method not found: {method}"}}


def _call_tool(name: str, arguments: object, catalog: Catalog) -> dict | list[dict]:
    if not isinstance(arguments, dict):
        raise ValueError("tool arguments must be an object")
    if name == "search":
        return catalog.search(
            str(arguments.get("query") or ""),
            str(arguments.get("kind") or "all"),
            arguments.get("limit", MAX_RESULTS),
        )
    if name == "get":
        return catalog.get(str(arguments.get("name") or ""), str(arguments.get("kind") or ""))
    if name == "get_reference":
        return catalog.get_reference(
            str(arguments.get("name") or ""),
            str(arguments.get("path") or ""),
            str(arguments.get("kind") or "skill"),
        )
    raise ValueError(f"unknown Coacus catalog tool {name!r}")


def serve(input_stream: TextIO, output_stream: TextIO, catalog: Catalog) -> None:
    """Serve newline-delimited JSON-RPC messages over MCP stdio."""
    for line in input_stream:
        if not line.strip():
            continue
        try:
            message = json.loads(line)
        except json.JSONDecodeError as exc:
            response = {"jsonrpc": "2.0", "id": None, "error": {"code": -32700, "message": f"Parse error: {exc.msg}"}}
        else:
            response = handle_message(message, catalog)
        if response is not None:
            output_stream.write(json.dumps(response, ensure_ascii=False, separators=(",", ":")) + "\n")
            output_stream.flush()


def main(argv: list[str] | None = None) -> int:
    """Start the server from the installed plugin directory or repo root."""
    import argparse

    parser = argparse.ArgumentParser(description="Coacus catalog MCP server")
    parser.add_argument(
        "--root",
        type=Path,
        default=None,
        help="Root directory containing catalog/index.json or Coacus repository root",
    )
    args = parser.parse_args(argv)
    root = (args.root or Path(__file__).resolve().parent).resolve()
    try:
        catalog = Catalog(root)
    except ValueError as exc:
        print(f"Catalog MCP startup error: {exc}", file=sys.stderr)
        return 2
    serve(sys.stdin, sys.stdout, catalog)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
